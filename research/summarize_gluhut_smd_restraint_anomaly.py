#!/usr/bin/env python3
"""Summarize chemical consistency of deposited GluHUT SMD restraint groups.

This consumes the deterministic atom mapping generated by
``audit_gluhut_smd_restraints.py``. It treats unexpected selections as evidence,
not as values to normalize away. The summary does not calculate work, PMFs,
affinity, or candidate performance.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
from typing import Any


def canonical_hash(value: Any) -> str:
    return hashlib.sha256(
        json.dumps(
            value,
            sort_keys=True,
            separators=(",", ":"),
            ensure_ascii=True,
        ).encode("utf-8")
    ).hexdigest()


def degrees(group: dict[str, Any]) -> dict[int, int]:
    result = {
        int(index): 0 for index in group["atom_indices_1_based"]
    }
    for left, right in group["induced_edges"]:
        result[int(left)] += 1
        result[int(right)] += 1
    return result


def two_core(group: dict[str, Any]) -> list[int]:
    """Return the graph 2-core, which isolates the selected cyclic core."""
    adjacency = {
        int(index): set() for index in group["atom_indices_1_based"]
    }
    for left, right in group["induced_edges"]:
        left = int(left)
        right = int(right)
        adjacency[left].add(right)
        adjacency[right].add(left)
    active = set(adjacency)
    changed = True
    while changed:
        changed = False
        remove = {
            atom
            for atom in active
            if sum(neighbour in active for neighbour in adjacency[atom]) < 2
        }
        if remove:
            active -= remove
            changed = True
    return sorted(active)


def atom_lookup(group: dict[str, Any]) -> dict[int, dict[str, Any]]:
    return {
        int(atom["atom_1_based"]): atom for atom in group["atoms"]
    }


def summarize_group(system_name: str, group: dict[str, Any]) -> dict[str, Any]:
    lookup = atom_lookup(group)
    atom_degrees = degrees(group)
    core = two_core(group)
    core_set = set(core)
    selected_hydrogens = [
        atom
        for atom in group["atoms"]
        if atom["element"] == "H"
    ]
    noncore = [
        lookup[index]
        for index in group["atom_indices_1_based"]
        if index not in core_set
    ]
    isolated = [
        lookup[index]
        for index, value in atom_degrees.items()
        if value == 0
    ]
    leaves = [
        lookup[index]
        for index, value in atom_degrees.items()
        if value == 1
    ]

    if selected_hydrogens:
        selection_class = "cyclic_core_plus_selected_hydrogen_or_mixed_atoms"
    elif noncore:
        selection_class = "cyclic_core_plus_exocyclic_heavy_atom"
    else:
        selection_class = "cyclic_heavy_atom_core_only"

    return {
        "system_name": system_name,
        "selection_class": selection_class,
        "selected_atom_count": group["atom_count"],
        "selected_atom_indices_1_based": group["atom_indices_1_based"],
        "selected_atom_names": [atom["atom_name"] for atom in group["atoms"]],
        "selected_elements": [atom["element"] for atom in group["atoms"]],
        "selected_hydrogen_atoms": selected_hydrogens,
        "selected_hydrogen_count": len(selected_hydrogens),
        "isolated_selected_atoms": isolated,
        "leaf_selected_atoms": leaves,
        "cyclic_core_atom_indices_1_based": core,
        "cyclic_core_atom_names": [lookup[index]["atom_name"] for index in core],
        "cyclic_core_atom_count": len(core),
        "noncore_selected_atoms": noncore,
        "connected_component_count": group["connected_component_count"],
        "induced_cycle_rank": group["induced_cycle_rank"],
        "selection_identity_sha256": canonical_hash(
            {
                "names": [atom["atom_name"] for atom in group["atoms"]],
                "elements": [atom["element"] for atom in group["atoms"]],
                "edges": group["induced_edges"],
            }
        ),
    }


def summarize(mapping_path: Path, output_path: Path) -> dict[str, Any]:
    mapping = json.loads(mapping_path.read_text(encoding="utf-8"))
    rows = sorted(mapping["mappings"], key=lambda row: row["system_name"])
    if {row["system_name"] for row in rows} != {
        "glucose",
        "galactose",
        "fructopyranose",
        "fructofuranose",
    }:
        raise ValueError("expected exactly the four public sugar systems")

    guest_summaries = [
        summarize_group(row["system_name"], row["group2"])
        for row in rows
    ]
    guest_by_system = {row["system_name"]: row for row in guest_summaries}

    host_groups = [row["group1"] for row in rows]
    host_component_sizes = sorted(
        [len(component) for component in host_groups[0]["component_atom_indices"]]
    )
    host_reference_is_two_six_carbon_rings = all(
        group["element_counts"] == {"C": 12}
        and group["amber_atom_type_counts"] == {"ca": 12}
        and group["connected_component_count"] == 2
        and sorted(len(component) for component in group["component_atom_indices"])
        == [6, 6]
        and group["induced_cycle_rank"] == 2
        for group in host_groups
    )

    core_parameter_keys = ("iat", "r2", "r2a", "rk2", "iresid")
    core_signatures = {
        canonical_hash(
            {key: row["parameters"].get(key) for key in core_parameter_keys}
        )
        for row in rows
    }
    full_parameter_signatures = {
        canonical_hash(row["parameters"]) for row in rows
    }

    fructofuranose = guest_by_system["fructofuranose"]
    glucose = guest_by_system["glucose"]
    galactose = guest_by_system["galactose"]
    fructopyranose = guest_by_system["fructopyranose"]

    guest_classes = {
        row["system_name"]: row["selection_class"]
        for row in guest_summaries
    }
    chemically_uniform = len(set(guest_classes.values())) == 1
    all_heavy = all(row["selected_hydrogen_count"] == 0 for row in guest_summaries)

    report = {
        "schema": "dia-health-one.gluhut-smd-restraint-consistency.v1",
        "status": "guest_reaction_coordinate_selection_inconsistent_author_clarification_required",
        "scope": "chemical interpretation of deposited public GluHUT SMD group selections",
        "not_target_claim": (
            "not NNC2215, PaG, MC-Q1, binding affinity, efficacy, safety, or a drug result"
        ),
        "source_mapping": {
            "path": str(mapping_path),
            "sha256": hashlib.sha256(mapping_path.read_bytes()).hexdigest(),
            "archive_md5": mapping["archive"]["md5"],
            "archive_sha256": mapping["archive"]["sha256"],
        },
        "host_reference_group": {
            "atom_indices_1_based": host_groups[0]["atom_indices_1_based"],
            "atom_names": [atom["atom_name"] for atom in host_groups[0]["atoms"]],
            "component_sizes": host_component_sizes,
            "all_atoms_are_aromatic_carbon_type_ca": all(
                group["element_counts"] == {"C": 12}
                and group["amber_atom_type_counts"] == {"ca": 12}
                for group in host_groups
            ),
            "same_mapped_identity_across_systems": mapping[
                "cross_system_summary"
            ]["host_group_mapped_identity_identical"],
            "two_six_member_aromatic_rings": host_reference_is_two_six_carbon_rings,
        },
        "guest_group_summaries": guest_summaries,
        "parameter_consistency": {
            "core_parameters_compared": list(core_parameter_keys),
            "core_parameters_identical": len(core_signatures) == 1,
            "all_recorded_parameters_identical": len(full_parameter_signatures) == 1,
            "per_system": {
                row["system_name"]: row["parameters"] for row in rows
            },
        },
        "cross_system_findings": {
            "guest_selection_classes": guest_classes,
            "guest_group_definitions_chemically_uniform": chemically_uniform,
            "all_guest_selections_are_heavy_atoms": all_heavy,
            "glucose_selection": (
                "six-member pyranose ring plus exocyclic C6"
                if glucose["selection_class"]
                == "cyclic_core_plus_exocyclic_heavy_atom"
                and glucose["noncore_selected_atoms"]
                and glucose["noncore_selected_atoms"][0]["atom_name"] == "C6"
                else "other"
            ),
            "galactose_selection": (
                "six-member pyranose ring plus exocyclic C6"
                if galactose["selection_class"]
                == "cyclic_core_plus_exocyclic_heavy_atom"
                and galactose["noncore_selected_atoms"]
                and galactose["noncore_selected_atoms"][0]["atom_name"] == "C6"
                else "other"
            ),
            "fructopyranose_selection": (
                "six-member ring heavy atoms only"
                if fructopyranose["selection_class"]
                == "cyclic_heavy_atom_core_only"
                else "other"
            ),
            "fructofuranose_selection": (
                "five-member ring plus isolated hydrogen H62"
                if fructofuranose["selected_hydrogen_count"] == 1
                and fructofuranose["selected_hydrogen_atoms"][0]["atom_name"]
                == "H62"
                and fructofuranose["cyclic_core_atom_count"] == 5
                else "other"
            ),
            "fructofuranose_selected_hydrogen_name": (
                fructofuranose["selected_hydrogen_atoms"][0]["atom_name"]
                if fructofuranose["selected_hydrogen_atoms"]
                else None
            ),
            "fructofuranose_selected_hydrogen_is_isolated": any(
                atom["atom_name"] == "H62"
                for atom in fructofuranose["isolated_selected_atoms"]
            ),
            "co_occurs_with_known_fructofuranose_us2_short_window_sensitivity_failure": True,
            "causal_link_to_short_window_failure_established": False,
        },
        "decision": {
            "host_reference_group_matches_two_aromatic_six_carbon_rings": (
                host_reference_is_two_six_carbon_rings
            ),
            "guest_reaction_coordinate_definition_is_uniform_across_sugars": (
                chemically_uniform
            ),
            "fructofuranose_group_contains_unexplained_hydrogen_H62": (
                fructofuranose["selected_hydrogen_count"] == 1
                and fructofuranose["selected_hydrogen_atoms"][0]["atom_name"]
                == "H62"
            ),
            "deposited_histogram_and_wham_reanalysis_remains_reproducible": True,
            "new_smd_or_umbrella_generation_authorized": False,
            "force_constant_convention_validated": False,
            "parent_pag_calibration_authorized": False,
            "candidate_ranking_authorized": False,
            "next_action": (
                "request author clarification or a corrected fructofuranose restraint; "
                "confirm why glucose/galactose include exocyclic C6 while fructopyranose "
                "uses ring atoms only; validate the rk2=200 and reported force-constant convention"
            ),
        },
        "limitations": [
            "This result interprets atom selections and compiled graph connectivity; it does not inspect trajectory coordinates or calculate centres of mass.",
            "The selected H62 may be intentional, a naming artifact, or a deposited input error; the audit cannot distinguish these without author clarification.",
            "The inconsistency does not invalidate reanalysis of the already deposited reaction-coordinate time series, but it blocks clean prospective regeneration and cross-sugar interpretation.",
            "No causal link is established between H62 selection and the separate fructofuranose US-2 short-window sensitivity failure.",
        ],
    }
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(
        json.dumps(report, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    return report


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--mapping-json",
        type=Path,
        default=Path("research/data/gluhut-smd-restraint-mapping.json"),
    )
    parser.add_argument(
        "--output-json",
        type=Path,
        default=Path("research/data/gluhut-smd-restraint-consistency.json"),
    )
    return parser


def main() -> int:
    args = build_parser().parse_args()
    report = summarize(args.mapping_json, args.output_json)
    print(
        json.dumps(
            {
                "host_reference_group": report["host_reference_group"],
                "cross_system_findings": report["cross_system_findings"],
                "decision": report["decision"],
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
